"""Order the members of the v2 API reference pages

The author's source order is the backbone: it groups things on purpose (building blocks,
then results, then responses; each union next to its variants). The reference graph only
makes two adjustments to it:

- each page opens with its entry points: the members closest to `Client` / `AsyncClient`
  by type references (the clients themselves on the interface page, `Report` on the
  report page, `ProofTerm` on the proof page, ...)
- helper functions nothing in the API reaches (`*_of_lib` converters) go to the end

Everything else stays where the author put it. Pages the clients don't reach at all
(`errors`, `decomp`) keep plain source order.

The order is written into each page as an explicit `members:` list, the same as if it
were written by hand.

    uv run --group docs python doc_order.py          # rewrite the pages
    uv run --group docs python doc_order.py --check  # exit 1 if a page is out of date (CI)
"""

import sys
from collections import deque
from pathlib import Path

import griffe

ROOTS = ["imandrax_api.v2.interface.Client", "imandrax_api.v2.interface.AsyncClient"]
ROOTS_SHORT = [r.rsplit(".", 1)[1] for r in ROOTS]
PAGES = {
    "interface": "imandrax_api.v2.interface",
    "mir": "imandrax_api.v2.mir",
    "evaluation_values": "imandrax_api.v2.evaluation_values",
    "decomp": "imandrax_api.v2.decomp",
    "errors": "imandrax_api.v2.errors",
    "report": "imandrax_api.v2.report",
    "proof": "imandrax_api.v2.proof",
}
DOCS = Path(__file__).parent / "docs" / "api"
HEADER = "<!-- Generated by doc_order.py, do not edit by hand -->\n"


def public_members(mod: griffe.Module) -> list[griffe.Object | griffe.Alias]:
    """What the page shows, in source order: `__all__` if the module declares it, else its
    own public members (so `from .mir import *` doesn't repeat mir on the interface page)"""
    if mod.exports is not None:
        names = [e if isinstance(e, str) else e.name for e in mod.exports]
        ms = [mod.members[n] for n in names]
    else:
        ms = [
            m
            for m in mod.members.values()
            if not m.is_alias and not m.name.startswith("_")
        ]
    return sorted(ms, key=lambda m: (m.alias_lineno if m.is_alias else m.lineno) or 0)


def exprs(obj: griffe.Object):
    """Every annotation, base class and alias value in `obj`, recursively"""
    if isinstance(obj, griffe.Class):
        yield from obj.bases
    if isinstance(obj, griffe.Function):
        yield obj.returns
        yield from (p.annotation for p in obj.parameters)
    if isinstance(obj, griffe.Attribute):
        yield obj.annotation
        yield obj.value  # type aliases: `X = A | B`
    if isinstance(obj, griffe.TypeAlias):  # `type X = A | B`
        yield obj.value
    for m in obj.members.values():
        if not m.is_alias:
            yield from exprs(m)


def refs(obj: griffe.Object) -> set[str]:
    out: set[str] = set()
    for e in exprs(obj):
        if isinstance(e, griffe.Expr):
            out |= {
                n.canonical_path
                for n in e.iterate(flat=True)
                if isinstance(n, griffe.ExprName)
            }
    return out


def distances(objs: dict[str, griffe.Object]) -> dict[str, int]:
    """Breadth-first search from the roots over type references"""
    edges = {path: refs(o) & objs.keys() for path, o in objs.items()}
    # A user given a base class gets its subclasses back, so a base also leads to them
    for path, o in objs.items():
        if isinstance(o, griffe.Class):
            for b in o.bases:
                if isinstance(b, griffe.Expr) and b.canonical_path in edges:
                    edges[b.canonical_path].add(path)
    dist = dict.fromkeys(ROOTS, 0)
    todo = deque(ROOTS)
    while todo:
        p = todo.popleft()
        for q in sorted(edges[p]):
            if q not in dist:
                dist[q] = dist[p] + 1
                todo.append(q)
    return dist


def order(
    ms: list[griffe.Object | griffe.Alias], dist: dict[str, int]
) -> list[griffe.Object | griffe.Alias]:
    """Entry points, then the rest in source order, then unreached helper functions"""
    reached = [dist[m.path] for m in ms if m.path in dist]
    if not reached:
        return ms
    entry = [m for m in ms if dist.get(m.path) == min(reached)]
    helpers = [m for m in ms if m.path not in dist and isinstance(m, griffe.Function)]
    moved = {m.path for m in entry + helpers}
    return entry + [m for m in ms if m.path not in moved] + helpers


def render(module: str, names: list[str]) -> str:
    lines = [
        HEADER,
        f"::: {module}",
        "    options:",
        "      members:",
    ]
    return "\n".join(lines + [f"        - {n}" for n in names]) + "\n"


def main() -> int:
    pkg = griffe.load("imandrax_api.v2", search_paths=[str(Path(__file__).parent)])
    members = {
        mod: public_members(pkg.modules_collection[mod]) for mod in PAGES.values()
    }
    # Re-exports (`__all__` naming an import) have no edges of their own
    dist = distances(
        {m.path: m for ms in members.values() for m in ms if not m.is_alias}
    )

    stale = []
    for page, mod in PAGES.items():
        ordered = order(members[mod], dist)
        if page == "interface" and [m.name for m in ordered[:2]] != ROOTS_SHORT:
            sys.exit(
                f"interface page should start with {ROOTS_SHORT}, got {ordered[:2]}"
            )
        path = DOCS / f"{page}.md"
        text = render(mod, [m.name for m in ordered])
        if path.read_text() != text:
            stale.append(path)
            if "--check" not in sys.argv:
                path.write_text(text)
    if stale and "--check" in sys.argv:
        print("Out of date, run `make docs-order`:", *map(str, stale), sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
